/**
 * Central API registry for the Developer Portal API Explorer.
 * Each entry describes a route: its HTTP method, path, functional category,
 * lifecycle tag (primary / fallback / legacy), what it does, and what it returns.
 */

export type HttpMethod = "GET" | "POST" | "PUT" | "PATCH" | "DELETE" | "OPTIONS";

export type LifecycleTag = "primary" | "fallback" | "legacy" | "internal" | "deprecated";

export type ApiCategory =
  | "Auth"
  | "User"
  | "BizCard"
  | "Company"
  | "Connections"
  | "Marketplace"
  | "Media"
  | "Messaging"
  | "Notifications"
  | "Portfolio"
  | "Products"
  | "SuperAdmin"
  | "Staff"
  | "Affiliate"
  | "Analytics"
  | "DevPortal"
  | "Cron"
  | "Payments"
  | "Geo"
  | "Debug";

export interface ApiEntry {
  id: string;
  method: HttpMethod;
  path: string;
  category: ApiCategory;
  lifecycle: LifecycleTag;
  summary: string;
  description: string;
  /** Human-readable shape of what the response data contains */
  returns: string;
  /** Auth requirements */
  auth: "session" | "superadmin" | "staff" | "dev" | "public" | "webhook";
  /** Approximate relative request volume: 1–5 */
  requestWeight?: number;
  /** If true, this endpoint is rate-limited */
  rateLimited?: boolean;
  /** Related endpoints by id */
  seeAlso?: string[];
  /** If true, side effects are irreversible */
  destructive?: boolean;
  /** Stable since version / date string */
  since?: string;
  /** Pages that fetch this endpoint (enriched by API explorer) */
  usedByPages?: Array<{
    path: string;
    label: string;
    portal: "dev" | "superadmin" | "admin" | "staff" | "user" | "public";
  }>;
}

