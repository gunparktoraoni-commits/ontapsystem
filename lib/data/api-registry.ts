/** Compute summary statistics across the registry */
export function computeRegistryStats(entries: ApiEntry[]) {
  const byMethod: Record<string, number> = {};
  const byLifecycle: Record<string, number> = {};
  const byCategory: Record<string, number> = {};
  const byAuth: Record<string, number> = {};

  for (const e of entries) {
    byMethod[e.method] = (byMethod[e.method] ?? 0) + 1;
    byLifecycle[e.lifecycle] = (byLifecycle[e.lifecycle] ?? 0) + 1;
    byCategory[e.category] = (byCategory[e.category] ?? 0) + 1;
    byAuth[e.auth] = (byAuth[e.auth] ?? 0) + 1;
  }

  return {
    totalEndpoints: entries.length,
    byMethod,
    byLifecycle,
    byCategory,
    byAuth,
  };
}
